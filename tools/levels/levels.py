#!/usr/bin/env python3
"""Turn the level files into game code and level-select pictures.

levels/classic.json and levels/island.json are the source of every board.
Each row is 12 cells written as two hexadecimal digits per cell.

    python3 tools/levels/levels.py generate          # write the .zi level code
    python3 tools/levels/levels.py generate --check  # fail if it is out of date
    python3 tools/levels/levels.py previews          # draw every level picture in both orientations
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
WIDTH, HEIGHT = 12, 20
CELLS = WIDTH * HEIGHT

# Classic kinds that are pieces standing on the floor rather than floor.
CLASSIC_PIECES = {1, 2, 3, 9, 19, 28, 36, 37, 38, 40, 72}
CLASSIC_ON_FLOOR = {15, 16, 17, 21, 25, 26, 27, 33, 34, 35}
CLASSIC_PLAYER = 10
ISLAND_PLAYER = 56


def load(edition):
    data = json.loads((ROOT / 'levels' / f'{edition}.json').read_text())
    levels = data['levels']
    if not levels or [level['number'] for level in levels] != list(range(1, len(levels) + 1)):
        raise SystemExit(f'{edition}: levels must be numbered from 1 without gaps')
    return levels


def cells(rows):
    if len(rows) != HEIGHT or any(len(row) != WIDTH * 2 for row in rows):
        raise SystemExit('Every board has 20 rows of 12 two-digit cells')
    text = ''.join(rows)
    int(text, 16)
    return [int(text[at:at + 2], 16) for at in range(0, len(text), 2)]


def classic_functions(levels):
    lines = ['ShoveyLevelData :: (number: s32) -> string {']
    for level in levels:
        cells(level['cells'])
        if 'tiles' in level:
            assert all(kind in {0,4,5,6,12,14,47,48,49,*range(57,79),*range(95,104)} for kind in cells(level['tiles']))
        if 'decorations' in level:
            assert 'tiles' in level and all(kind in {0, 57, 58, 59, 84, 106, 122} for kind in cells(level['decorations']))
        data = ''.join(level['cells']) + ''.join(level.get('tiles', [])) + ''.join(level.get('decorations', []))
        lines.append(f'    if number == {level["number"]} {{ return "{data}" }}')
    lines += ['    return ""', '}', '', 'ShoveyLevelSolution :: (number: s32) -> string {']
    for level in levels:
        solution = level.get('solution', '')
        lines.append(f'    if number == {level["number"]} {{ return "{solution}" }}')
    lines += ['    return ""', '}', '']
    return '\n'.join(lines)


def classic_code(levels):
    approved_levels = json.loads((ROOT / 'levels/approved.json').read_text())['levels']
    approved = len(approved_levels)
    assert 1 <= approved < len(levels)
    assert [level['number'] for level in approved_levels] == list(range(1, approved + 1))
    return ('// Generated by tools/levels/levels.py from levels/classic.json.\n'
            f'SHOVEY_LEVEL_COUNT :: {len(levels)}\nSHOVEY_APPROVED_LEVEL_COUNT :: {approved}\n\n'
            '#if #defined(SHOVEY_RELEASE) {\n' + classic_functions(approved_levels) +
            '} else {\n' + classic_functions(levels) + '}\n')


def island_code(levels):
    lines = ['// Generated by tools/levels/levels.py from levels/island.json.',
             '// Two 12 by 20 layers: terrain, then objects.',
             '#if #defined(SHOVEY_RELEASE) {', 'ISLAND_LEVEL_COUNT :: 0',
             'IslandLevelData :: (number: s32) -> string { return "" }',
             'IslandLevelSolution :: (number: s32) -> string { return "" }',
             'IslandLevelName :: (number: s32) -> string { return "" }',
             '} else {', f'ISLAND_LEVEL_COUNT :: {len(levels)}', 'IslandLevelData :: (number: s32) -> string {']
    for level in levels:
        cells(level['terrain'])
        cells(level['objects'])
        data = ''.join(level['terrain']) + ''.join(level['objects'])
        lines.append(f'    if number == {level["number"]} {{ return "{data}" }}')
    lines += ['    return ""', '}', '', 'IslandLevelSolution :: (number: s32) -> string {']
    for level in levels:
        solution = level.get('solution', '')
        lines.append(f'    if number == {level["number"]} {{ return "{solution}" }}')
    lines += ['    return ""', '}', '', 'IslandLevelName :: (number: s32) -> string {']
    for level in levels:
        lines.append(f'    if number == {level["number"]} {{ return {json.dumps(level["name"], ensure_ascii=False)} }}')
    lines += ['    return ""', '}', '}', '']
    return '\n'.join(lines)


def generate(check):
    outputs = {
        ROOT / 'src/levels.zi': classic_code(load('classic')),
        ROOT / 'src/island_levels.zi': island_code(load('island')),
    }
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if check:
        for path in stale:
            print(f'out of date: {path.relative_to(ROOT)}')
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
    print(f'wrote {len(outputs)} level files')
    return 0


class Sprites:
    """Sprites scaled once to the preview cell size."""

    def __init__(self, folder, cell):
        from PIL import Image
        self.Image = Image
        self.folder = folder
        self.cell = cell
        self.cache = {}

    def get(self, name):
        if name not in self.cache:
            image = self.Image.open(self.folder / f'{name}.png').convert('RGBA')
            self.cache[name] = image.resize((self.cell, self.cell), self.Image.LANCZOS)
        return self.cache[name]


def save(image, path):
    # A shared palette keeps 350 pictures small without visible banding.
    image = image.convert('RGB').quantize(colors=192, method=2, dither=1)
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)


def previews(cell):
    from PIL import Image
    size = (WIDTH * cell, HEIGHT * cell)
    turned_size = (HEIGHT * cell, WIDTH * cell)
    sprites = Sprites(ROOT / 'assets/shovey/sprites', cell)
    turned_sprites = Sprites(ROOT / 'assets/shovey-landscape/sprites', cell)
    for level in load('classic'):
        board = cells(level['cells'])
        floor_tiles = cells(level['tiles']) if 'tiles' in level else [77 if kind == 7 else 0 for kind in board]
        decorations = cells(level['decorations']) if 'decorations' in level else [0] * CELLS
        image = Image.new('RGBA', size)
        turned = Image.new('RGBA', turned_size)
        for at, kind in enumerate(board):
            x, y = at % WIDTH * cell, at // WIDTH * cell
            display = (WIDTH - 1 - at % WIDTH) * HEIGHT + at // WIDTH
            turned_x, turned_y = display % HEIGHT * cell, display // HEIGHT * cell
            tile = floor_tiles[at]
            image.alpha_composite(sprites.get(f'tile-{tile}'), (x, y))
            turned.alpha_composite(turned_sprites.get(f'tile-{tile}'), (turned_x, turned_y))
            if decorations[at]:
                image.alpha_composite(sprites.get(f'tile-{decorations[at]}'), (x, y))
                turned.alpha_composite(turned_sprites.get(f'tile-{decorations[at]}'), (turned_x, turned_y))
            if kind == CLASSIC_PLAYER:
                image.alpha_composite(sprites.get('player-up'), (x, y))
                turned.alpha_composite(turned_sprites.get('player-up'), (turned_x, turned_y))
            elif kind != 0:
                image.alpha_composite(sprites.get(f'tile-{kind}'), (x, y))
                turned.alpha_composite(turned_sprites.get(f'tile-{kind}'), (turned_x, turned_y))
        save(image, ROOT / f'assets/shovey/levels/{level["number"]}.png')
        save(turned, ROOT / f'assets/shovey/levels-landscape/{level["number"]}.png')
    tiles = Sprites(ROOT / 'assets/shovey-island/tiles', cell)
    players = Sprites(ROOT / 'assets/shovey-island/player', cell)
    turned_tiles = Sprites(ROOT / 'assets/shovey-island-landscape/tiles', cell)
    turned_players = Sprites(ROOT / 'assets/shovey-island-landscape/player', cell)
    for level in load('island'):
        terrain, objects = cells(level['terrain']), cells(level['objects'])
        image = Image.new('RGBA', size)
        turned = Image.new('RGBA', turned_size)
        for at, kind in enumerate(terrain):
            x, y = at % WIDTH * cell, at // WIDTH * cell
            image.alpha_composite(tiles.get(str(kind)), (x, y))
            display = (WIDTH - 1 - at % WIDTH) * HEIGHT + at // WIDTH
            turned_x, turned_y = display % HEIGHT * cell, display // HEIGHT * cell
            turned.alpha_composite(turned_tiles.get(str(kind)), (turned_x, turned_y))
        for at, kind in enumerate(objects):
            position = (at % WIDTH * cell, at // WIDTH * cell)
            display = (WIDTH - 1 - at % WIDTH) * HEIGHT + at // WIDTH
            turned_position = (display % HEIGHT * cell, display // HEIGHT * cell)
            if kind == ISLAND_PLAYER:
                image.alpha_composite(players.get('1'), position)
                turned.alpha_composite(turned_players.get('1'), turned_position)
            elif kind:
                image.alpha_composite(tiles.get(str(kind)), position)
                turned.alpha_composite(turned_tiles.get(str(kind)), turned_position)
        save(image, ROOT / f'assets/shovey-island/levels/{level["number"]}.png')
        save(turned, ROOT / f'assets/shovey-island/levels-landscape/{level["number"]}.png')
    print(f"drew {len(load('classic')) + len(load('island'))} level pictures")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest='command', required=True)
    command = commands.add_parser('generate')
    command.add_argument('--check', action='store_true')
    command = commands.add_parser('previews')
    command.add_argument('--cell', type=int, default=16)
    args = parser.parse_args()
    if args.command == 'generate':
        return generate(args.check)
    return previews(args.cell)


if __name__ == '__main__':
    sys.exit(main())

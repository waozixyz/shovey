"""Generate the shipped Island prefix without changing the design source."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def shipped_levels(root=ROOT):
    config = json.loads((root / 'packaging/island-campaign.json').read_text())
    count = config['shipped_levels']
    if not 1 <= count <= config['planned_levels'] <= 175:
        raise ValueError('Island campaign exceeds its save capacity')
    return count


def stage_assets(resources, root=ROOT):
    """Remove later board previews from the disposable package staging area."""
    count = shipped_levels(root)
    for folder in ('levels', 'levels-landscape'):
        for path in (resources / folder).glob('*.png'):
            if path.stem.isdecimal() and int(path.stem) > count:
                path.unlink()
    art_path = resources / 'art.json'
    art = json.loads(art_path.read_text())
    art['files'] = [item for item in art['files'] if (resources / item['path']).is_file()]
    art_path.write_text(json.dumps(art, indent=2) + '\n')


def generate(root=ROOT):
    count = shipped_levels(root)
    source = json.loads((root / 'levels/island.json').read_text())
    levels = source['levels'][:count]
    if [level['number'] for level in levels] != list(range(1, count + 1)):
        raise ValueError('Island needs a complete sequential shipped campaign')
    functions = [
        ('IslandLevelData', 'string', lambda level: ''.join(
            ''.join(level[layer]) for layer in ('ground', 'features', 'objects')), ''),
        ('IslandLevelSolution', 'string', lambda level: level['solution'], ''),
        ('IslandLevelName', 'string', lambda level: level['name'], ''),
        ('IslandLevelKeepsake', 's32', lambda level: level.get('keepsake', 0), 0),
        ('IslandLevelKeepsakeSolution', 'string', lambda level: level.get('keepsake_solution', ''), ''),
    ]
    code = '// Generated by scripts/island_campaign.py; design source remains in levels/island.json.\n'
    code += '#if #defined(SHOVEY_RELEASE) || #defined(SHOVEY_ADMIN) {\nISLAND_LEVEL_COUNT :: 0\n'
    for name, kind, value, empty in functions:
        code += f'{name} :: (number: s32) -> {kind} {{ return {json.dumps(empty)} }}\n'
    code += f'}} else {{\nISLAND_LEVEL_COUNT :: {count}\n'
    for name, kind, value, empty in functions:
        code += f'{name} :: (number: s32) -> {kind} {{\n'
        for level in levels:
            result = value(level)
            if name == 'IslandLevelData' and len(result) != 1440:
                raise ValueError('Island board needs three 12 by 20 layers')
            code += f'    if number == {level["number"]} {{ return {json.dumps(result, ensure_ascii=False)} }}\n'
        code += f'    return {json.dumps(empty)}\n}}\n\n'
    code += '}\n'
    (root / 'src/island_levels.zi').write_text(code)
    return count


if __name__ == '__main__':
    print(f'Generated {generate()} shipped Island levels')
